def decode(model):
    """从型号解码 阻力/最低高度/最高高度（高度单位 dm→m），实现型号与参数自动对拍"""
    m = re.search(r"[A-Z]+?(\d+(?:\.\d+)?)/(\d+(?:\.\d+)?)/(\d+(?:\.\d+)?)", model)
    return int(float(m.group(1))), float(m.group(2)) / 10, float(m.group(3)) / 10

rows, bad = [], []
for line in RAW.strip().splitlines():
    line = line.strip()
    if not line or line.startswith("#"):
        continue
    model, typ, cd, src = [x.strip() for x in line.split("|")]
    try:
        r, h1, h2 = decode(model)
    except Exception:
        bad.append(model); continue
    row = {"model": model, "type": typ, "resistance": r,
           "height_min": h1, "height_max": h2, "center_dist": float(cd),
           "canopy_len": None, "intensity": None, "initial_force": None,
           "floor_pressure": None, "weight": None, "manufacturer": None,
           "source": src}
    row.update(EXTRA.get(model, {}))
    rows.append(row)

